#!/usr/bin/env python3
"""Roadmap builder — purpose: map.json -> curriculum/roadmap.md (waves -> seasons -> episodes).
Owner doc: build/master-plan.md §5. Flags: --dry-run --debug. EDIT: SEASONS below."""
import json, sys, collections
M=json.load(open('out/map.json')); C=M['concepts']; byId={o['id']:o for o in C}
# EDIT: seasons (wave, id, question, chapters). S1 pilot is fixed (S1E01 Gastrulation, episode catalog).
SEASONS=[
 (1,'S1','How does a flat disc become a body?',['E05','E06','E07']),
 (2,'S2','Where does it all begin?',['E02','E03','E04']),
 (2,'S3','How do cells tell each other what to become?',['E01']),
 (2,'S4','How does the embryo live — and what can go wrong?',['E08','E09']),
 (3,'S5','How does a tube become a heart?',['E13']),
 (3,'S6','How does one tube make the gut and lungs?',['E14','E15']),
 (4,'S7','Kidneys and sex: why one ridge does two jobs',['E16']),
 (4,'S8','How do arch-shaped bars build a face, an ear and an eye?',['E17','E19','E20']),
 (5,'S9','How does a tube become a brain?',['E18']),
 (5,'S10','Bones, muscles, limbs and skin',['E10','E11','E12','E21']),
]
WAVES={0:'Orientation (Part 0) — cards only',1:'Season 1 — the body plan (pilot season)',2:'Beginnings and support (Part 1 rest)',3:'Systems I — heart, gut, lungs',4:'Systems II — urogenital, head & neck, senses',5:'Systems III — CNS, musculoskeletal, skin'}
KEEP={'core','exam-high'}
DEP={}
def depth(i):
    if i not in DEP: DEP[i]=1+max([depth(p) for p in byId[i]['prereq']] or [0])
    return DEP[i]
def topo(ids):
    ids=set(ids); out=[]; seen=set()
    def v(i):
        if i in seen or i not in ids: return
        seen.add(i)
        for p in byId[i]['prereq']: v(p)
        out.append(i)
    for i in sorted(ids,key=lambda i:(-byId[i]['unlock_n'],i)): v(i)
    return out
L=['# Roadmap — Langman 14e (E)\n','*(Purpose: step-by-step order to cover every core and exam-high concept: waves → seasons → episodes. Updated: 17 Nov 2026 · Bio · Build · K1 concept map. Rebuilt after every use gate.)*\n',
 '**How it is ordered:** prerequisites first (topological order), then by unlock count (concepts that open the most later ones go first). Source: `curriculum/concept-map.md` / `content/E/map.json`. Generated by `tools/map/roadmap.py`; edit seasons there, not here.\n',
 '**Episode ids** below are *provisional slots* (S2E03…) — an id becomes permanent only when its row is added to `curriculum/episodes-catalog.md` (A2). S1E01 is already fixed. ★ = core tag (×2); others are support (×1). Every season ends with a recap / connect-the-dots episode (D7). Clinical (Tier C) concepts become Mystery cold opens inside the episode that teaches the normal process.\n']
cov=set(); tot=[o['id'] for o in C if o['importance'] in KEEP]
L.append(f'**Coverage target:** {len(tot)} concepts (core {sum(o["importance"]=="core" for o in C)} + exam-high {sum(o["importance"]=="exam-high" for o in C)}).\n')
# wave 0
L.append('\n## Wave 0 · '+WAVES[0]+'\n')
L.append('Cards E00.01.01–06 (C1, first batch). No episode; every episode links back to them. **Work:** C1 Part 0. **Owner check:** T3 (cards on phone).\n')
cov|={o['id'] for o in C if o['ch']=='E00' and o['importance'] in KEEP}
epcount=0
for w in range(1,6):
    L.append(f'\n## Wave {w} · {WAVES[w]}\n')
    ss=[s for s in SEASONS if s[0]==w]
    work={1:'X1 Ch 05–07 → C1 (Ch 5 Tier A first) → P1 S1E01 animatic → R1 → L1 → use gate',2:'X1 Ch 01–04, 08–09 → C1 → episodes',3:'X1 Ch 13–15 → C1 → episodes',4:'X1 Ch 16, 17, 19, 20 → C1 → episodes',5:'X1 Ch 10–12, 18, 21 → C1 → episodes'}[w]
    L.append(f'**Work:** {work}. **Gates:** G-Sci, G-Learn (cards); + G-Story, G-Art (episodes). **Owner checks:** card skim per chapter; watch each episode on the phone; season use gate (24 h + 7 d cold Checks).\n')
    for _,sid,q,chs in ss:
        ids=[o['id'] for o in C if o['ch'] in chs and o['importance'] in KEEP]
        order=topo(ids)
        L.append(f'\n### {sid} — “{q}” · {", ".join(chs)} · {len(order)} concepts\n')
        L.append('| Ep | Working title | Cards (★ core) | Needs from earlier |\n|---|---|---|---|')
        # group into episodes by section, <=4 concepts each, in topo order of first appearance
        groups=collections.OrderedDict()
        for i in order: groups.setdefault(byId[i]['sec'],[]).append(i)
        eps=[]
        for sec,lst in groups.items():
            nonclin=[i for i in lst if byId[i]['tier']!='C']; clin=[i for i in lst if byId[i]['tier']=='C']
            chunks=[nonclin[k:k+4] for k in range(0,len(nonclin),4)] or [[]]
            chunks[-1]+=clin  # clinical rides with the last chunk as its mystery
            for ch in chunks:
                if ch: eps.append((sec,ch))
        # merge tiny eps (1 concept) into previous of same chapter
        merged=[]
        for sec,ch in eps:
            if merged and len(ch)==1 and merged[-1][0][:3]==sec[:3] and len(merged[-1][1])<5: merged[-1]=(merged[-1][0],merged[-1][1]+ch)
            else: merged.append((sec,ch))
        merged.sort(key=lambda m:m[0])  # book order; violations reported below
        n=0; pilot=[]
        if sid=='S1':  # pilot fixed
            pilot=['E05.01.01','E05.01.02','E05.01.03','E05.01.04']
            L.append(f"| **S1E01** | Gastrulation (pilot, fixed) | ★{', ★'.join(pilot)} · E05.02.01, E00.01.04 | E04.01.01 Bilaminar disc |")
            cov|=set(pilot); n=1
            merged=[(s,[i for i in c if i not in pilot]) for s,c in merged]; merged=[m for m in merged if m[1]]
        for sec,ch in merged:
            n+=1; core=[i for i in ch if byId[i]['importance']=='core' or byId[i]['tier']!='C' and byId[i]['importance']=='exam-high' and len(ch)<=2]
            if not core: core=ch[:1]
            title=byId[[i for i in ch if byId[i]['tier']!='C'][0] if any(byId[i]['tier']!='C' for i in ch) else ch[0]]['name']
            need=sorted({p for i in ch for p in byId[i]['prereq'] if byId[p]['ch'] not in chs})
            cards=', '.join(('★' if i in core else '')+i for i in ch)
            L.append(f"| {sid}E{n:02d} | {title} | {cards} | {', '.join(need[:4]) or '—'} |")
            cov|=set(ch)
        pos={}; k=0
        for _s,ch in merged:
            k+=1
            for i in ch: pos[i]=k
        for i in pilot if sid=='S1' else []: pos[i]=0
        late=[f"{i}←{p}" for i in pos for p in byId[i]['prereq'] if p in pos and pos[p]>pos[i]]
        note=(f"\n*Order note:* these cards meet a prerequisite taught later in the season — the episode gives a 1-line preview: {', '.join(late)}\n") if late else None
        n+=1; L.append(f"| {sid}E{n:02d} | Recap — connect the dots ({', '.join(chs)}) | review of the season's ★ cards | — |")
        if note: L.append(note)
        epcount+=n
miss=[i for i in tot if i not in cov]
L.append(f'\n---\n**Totals:** {epcount} planned episodes in 10 seasons · core + exam-high covered: {len(set(tot)&cov)}/{len(tot)}' + (f' · missing: {", ".join(miss)}' if miss else ' ✅') + '.\n')
L.append('**Supporting and detail concepts** become cards in the same waves (card-only, tagged support where an episode uses them).\n')
L.append('**Re-plan rule:** after each use gate, the Review chat reorders the next wave by recall results and weak spots (master plan §9); ids already in the catalog never change.\n')
open('out/roadmap.md','w').write('\n'.join(L)); print(epcount,len(set(tot)&cov),len(tot),miss)
