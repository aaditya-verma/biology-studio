"""Kinetic captions for the M1b host shot: ASS (burned into the Short) + WebVTT (toggleable in the app).
Owner doc: build/visual-style.md §1 (captions band, sizes, scrim) · studio-playbook.md §5b (kinetic captions) · spec: host.json › captions.
One phrase at a time, synced to Kokoro word timings; key words in the key colour + weight; then one Hindi line (Devanagari).
Usage: python captions.py [--res ship|design|preview] [--debug] [--dry-run]"""
import argparse, json, os

KIT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(KIT, "out")


def ass_col(hexs, alpha=0.0):
    h = hexs.lstrip("#")
    return "&H%02X%s%s%s" % (int(alpha * 255), h[4:6], h[2:4], h[0:2])  # ASS = AABBGGRR, alpha 00 = opaque


def ts_ass(t):
    t = max(0.0, t); h = int(t // 3600); m = int(t % 3600 // 60); s = t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def ts_vtt(t):
    t = max(0.0, t); m = int(t // 60); s = t % 60
    return f"00:{m:02d}:{s:06.3f}"


def phrases(spec, words, lead, track="en"):
    """EN: group Kokoro words into host.json phrases (by word count). HI: split the spoken span evenly."""
    C = spec["captions"]; out, i = [], 0
    end = spec["video"]["seconds"]
    if track == "hi":
        t0 = lead + (words[0]["t0"] if words else 0); t1 = lead + (words[-1]["t1"] if words else end - lead)
        n = len(C["phrases_hi"]); step = (t1 - t0) / n
        if C.get("hi_times_s"):  # EDIT: explicit starts in host.json win over the even split
            ts = C["hi_times_s"] + [end]
            return [[ts[k], ts[k + 1], ph] for k, ph in enumerate(C["phrases_hi"])]
        return [[t0 + k * step, (t0 + (k + 1) * step) if k + 1 < n else end, ph] for k, ph in enumerate(C["phrases_hi"])]
    for ph in C["phrases_en"]:
        n = len(ph.split())
        ws = words[i:i + n] if i + n <= len(words) else words[i:]
        t0 = (ws[0]["t0"] if ws else (out[-1][1] if out else 0)) + (lead if ws else 0)
        out.append([t0, None, ph]); i += n
    for k in range(len(out)):
        out[k][1] = out[k + 1][0] if k + 1 < len(out) else end
    return out


def mark_key(text, key, col, plain_col, C=None):
    """Key words: colour AND heavier weight AND slight scale (never colour alone — H5)."""
    if key and key.rstrip("?") in text:
        k = key.rstrip("?"); C = C or {}
        w = C.get("key_weight", 900); sc = round(100 * C.get("key_scale", 1.08))
        return text.replace(k, "{\\c%s\\b%d\\fscx%d\\fscy%d}%s{\\c%s\\b1\\fscx100\\fscy100}" % (col, w, sc, sc, k, plain_col))
    return text


def build(spec, words, lead, res, track="en", rm=False):
    C = spec["captions"]; W, Hh = {"design": spec["video"]["design"], "ship": spec["video"]["ship"], "preview": spec["video"]["preview"]}[res]
    k = W / 1080.0
    size = round(C["size_px_1080"] * k); size_hi = round(size * C["deva_scale"])
    y = round(Hh * (C["band_top_pct"] + C["band_bottom_pct"]) / 200)
    margin = round(W * (1 - C["max_width_pct"] / 100) / 2)
    white, key = ass_col(C["text"]), ass_col(C["key"])
    tag = lambda hx: "&H%s%s%s&" % (hx[5:7], hx[3:5], hx[1:3])  # inline \c takes BGR, no alpha
    kc, wc = tag(C["key"]), tag(C["text"])
    box = ass_col(C["outline"], 1 - C["scrim_alpha"])
    pad = max(2, round(10 * k))
    head = f"""[Script Info]
; Purpose: M1b kinetic captions (visual-style §1). Generated by captions.py — edit host.json, not this file.
ScriptType: v4.00+
PlayResX: {W}
PlayResY: {Hh}
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: EN,{C['font_latin']},{size},{white},{white},{box},{box},1,0,0,0,100,100,0,0,3,{pad},0,5,{margin},{margin},0,1
Style: HI,{C['font_deva']},{size_hi},{white},{white},{box},{box},1,0,0,0,100,100,0,0,3,{pad},0,5,{margin},{margin},0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    pop = "{\\an5\\pos(%d,%d)}" % (W // 2, y) if rm else \
        "{\\an5\\pos(%d,%d)\\fscx86\\fscy86\\t(0,120,\\fscx100\\fscy100)}" % (W // 2, y)  # EDIT: pop-in (120 ms, no flashing); none in reduced motion
    ev, vtt = [], ["WEBVTT", ""]
    sty, key_ = ("HI", spec["line"]["key_hi"]) if track == "hi" else ("EN", spec["line"]["key_en"])
    for t0, t1, ph in phrases(spec, words, lead, track):
        ev.append(f"Dialogue: 0,{ts_ass(t0)},{ts_ass(t1)},{sty},,0,0,0,,{pop}{mark_key(ph, key_, kc, wc, C)}")
        vtt += [f"{ts_vtt(t0)} --> {ts_vtt(t1)} line:60%", ph, ""]
    return head + "\n".join(ev) + "\n", "\n".join(vtt)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default="ship"); ap.add_argument("--debug", action="store_true")
    ap.add_argument("--dry-run", action="store_true"); ap.add_argument("--only"); ap.add_argument("--preview", action="store_true")
    ap.add_argument("--reduced-motion", action="store_true")
    a = ap.parse_args()
    res = "preview" if a.preview else a.res
    spec = json.load(open(os.path.join(KIT, "host.json"), encoding="utf-8"))
    wj = json.load(open(os.path.join(OUT, "audio", "words.json"), encoding="utf-8"))
    d = os.path.join(OUT, "captions"); os.makedirs(d, exist_ok=True)
    rm = a.reduced_motion
    for tr in spec["captions"]["tracks"]:
        ass, vtt = build(spec, wj["words"], wj["lead_in_s"], res, tr, rm)
        if a.debug or a.dry_run:
            print(ass); print(vtt)
        if a.dry_run:
            continue
        open(os.path.join(d, f"captions_{tr}_{res}{'_rm' if rm else ''}.ass"), "w", encoding="utf-8").write(ass)
        open(os.path.join(d, f"captions_{tr}.vtt"), "w", encoding="utf-8").write(vtt)
    print("[captions] wrote", d)


if __name__ == "__main__":
    main()
